#!/usr/bin/env python3
"""Names in the forms a port, a debugger or a disassembler can load, and a quality audit of the catalog.

Called by progress.py (outputs go to docs/progress, regenerated by CI). Stand-alone:

  export_names.py [--out DIR]     write the files from DIR/functions.json
  export_names.py --audit         print the audit only

Outputs
  function_names.sym   `ADDRESS Name` per line (mGBA / no$gba symbol file; also easy to import in Ghidra/IDA)
  function_names.h     `#define Name sub_XXXXXXXX`, so port code can call functions by display name
  function_names.csv   address, symbol, name, system, module, size, status
  name_audit.md        naming-quality findings for reviewers

`system` is a coarse subsystem tag taken from the words of the display name. It is a reading aid for
planning a port (what touches audio, video, link, save...), not evidence about the function.
"""
import argparse, collections, csv, io, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# First matching rule wins; order goes from platform-facing to gameplay.
SYSTEMS = [
    ("scheduler", r"^Task(Wait|Yield|Sleep)|Scheduler|Coroutine|^Yield|Signal\d|Thread"),
    ("interrupt", r"Interrupt|VBlank|HBlank|Irq"),
    ("audio", r"Audio|Song|Sound|Music|MPlay|Voice|Cgb|^m4a|^Sample|^ply_|^Clear_?Chn|^Track|^FadeOut|^MidiKey"),
    ("link", r"Link|Multiplayer|Sio|Serial|Cable|Participant"),
    ("save", r"Save|Flash|Sram|Checksum|Backup"),
    ("video", r"Bg\d?[A-Z]|^Bg|Background|Palette|Blend|Affine|Dma|Vram|Oam|Tilemap|ScreenBlock|Display|Mosaic|WindowReg|Fade|Lz77|Decompress"),
    ("sprite", r"Sprite|Animation|Animate|Frame"),
    ("resource", r"Resource|Asset|Graphics|Load"),
    ("text", r"Text|Font|Glyph|Message|Dialog|String"),
    ("menu", r"Menu|Cursor|Selection|Shop|Inventory|Bag|Equipment|Title|Option|SoundTest"),
    ("hud", r"Hud|Gauge|Meter|Icon|Indicator"),
    ("map", r"Map|Area|World|Scroll|Camera|Tile|Collision|Room|Dungeon|Stage"),
    ("item", r"Item|Currency|Gold|Drop|Chest|Recipe|Collection"),
    ("combat", r"Attack|Damage|Hit|Projectile|Skill|Ability|Charged|Status|Knockback|Weapon"),
    ("enemy", r"Enemy|Boss|Encounter|Spawn|Monster"),
    ("player", r"Player|Character|Class|Level|Experience"),
    ("scene", r"Scene|Event|Cutscene|Sequence|Transition"),
    ("actor", r"Actor|Entity|Object|Effect|Particle"),
    ("math", r"Fixed|Random|Sine|Cosine|Sqrt|Divide|Multiply|Interpolate|Distance|Direction|Angle|Q\d"),
    ("memory", r"Allocate|Free|Pool|Heap|Copy|Fill|Clear|Zero|Memory"),
    ("input", r"Key|Button|Input|Pad"),
]
SYSTEMS = [(name, re.compile(rule)) for name, rule in SYSTEMS]

# Spelling families that should use one word. The first form is the house style.
VOCABULARY = [("Dialogue", ["Dialog"]), ("Initialize", ["Init"]), ("Background", ["Backdrop"]),
              ("Animation", ["Anim"]), ("Position", ["Pos"]), ("Palette", ["Pal"]), ("Cleanup", ["CleanUp"])]


def words(name):
    return re.findall(r"[A-Z][a-z]+|[A-Z]+(?![a-z])|\d+", name)


def system_of(node):
    name = node.get("display_name") or ""
    if node.get("cat") == "lib" or node.get("domain") == "sdk":
        return "sdk"
    if node.get("name_status") not in ("confirmed", "existing"):
        return ""
    for system, rule in SYSTEMS:
        if rule.search(name):
            return system
    return "game"


def audit(nodes):
    game = [n for n in nodes if n.get("cat") == "game" and n.get("name_status") in ("confirmed", "existing")]
    names = {n["display_name"]: n for n in game}
    out = ["# Function name audit", "",
           "Generated from the catalog. Each list is a queue for a reviewer; nothing here is an error by itself.", ""]

    def section(title, why, rows, limit=400):
        out.extend(["## %s (%d)" % (title, len(rows)), "", why, ""])
        out.extend("- `%s` %s — %s" % (n["canonical_symbol"], n["display_name"], note) for n, note in rows[:limit])
        if len(rows) > limit:
            out.append("- ... %d more" % (len(rows) - limit))
        out.append("")

    numbered = collections.defaultdict(list)
    for n in game:
        m = re.fullmatch(r"(.*?)(?:Variant)?(\d+)", n["display_name"])
        if m and not re.search(r"(Bg|Dma|Q|Random|Lz|Palette|Signal|Low|Timer|Channel|Player|Direction|Stub)$", m[1]):
            numbered[m[1]].append(n)
    section("Numbered siblings", "Several functions share one name and differ only by a number. For a port they "
            "should say what differs (the table that stores them, the scene, the parameter).",
            [(n, "family `%s`, %d members" % (k, len(v))) for k, v in sorted(numbered.items()) if len(v) > 1 for n in v])
    section("Wrappers and thunks", "The name describes the shape, not the purpose. Fine for a true tail call; "
            "name the caller's intent when there is one.",
            [(n, "") for n in game if re.search(r"(Wrapper|Thunk|Stub)$", n["display_name"])])
    section("Internal ids in the name", "Type, mode, state or op numbers that mean nothing outside the ROM. "
            "Replace by what the id is once the table that defines it is named.",
            [(n, "") for n in game if re.search(r"(Type|Mode|State|Kind|Op|Slot|Case|Phase)\d+", n["display_name"])])
    section("Very long names", "More than 44 characters or 8 words: usually two behaviours joined by And/With/Or. "
            "Prefer the purpose over the list of effects.",
            [(n, "%d chars" % len(n["display_name"])) for n in game
             if len(n["display_name"]) > 44 or len(words(n["display_name"])) > 8])
    vocabulary = []
    for good, variants in VOCABULARY:
        for n in game:
            parts = words(n["display_name"])
            for v in variants:
                if v in parts:
                    fixed = "".join(good if p == v else p for p in parts)
                    vocabulary.append((n, "use `%s`%s" % (fixed, " (taken)" if fixed in names else "")))
    section("Vocabulary", "One concept, one word.", vocabulary)
    counts = collections.Counter(system_of(n) for n in game)
    out.extend(["## Functions per system", "", "| System | Functions |", "| --- | ---: |"])
    out.extend("| %s | %d |" % kv for kv in counts.most_common())
    out.append("")
    return "\n".join(out)


def write_outputs(nodes, out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    named = [n for n in nodes if n.get("name_status") in ("confirmed", "existing")]
    named.sort(key=lambda n: n["addr"])
    (out / "function_names.sym").write_text(
        "".join("%08X %s\n" % (n["addr"] & ~1, n["display_name"]) for n in named), encoding="utf-8", newline="\n")
    header = ["/* Generated by tools/scripts/export_names.py: display names for canonical symbols. */",
              "#ifndef SS2_FUNCTION_NAMES_H", "#define SS2_FUNCTION_NAMES_H", ""]
    header += ["#define %s %s" % (n["display_name"], n["canonical_symbol"]) for n in named
               if n["display_name"] != n["canonical_symbol"] and re.fullmatch(r"[A-Za-z_]\w*", n["display_name"])]
    (out / "function_names.h").write_text("\n".join(header + ["", "#endif", ""]), encoding="utf-8", newline="\n")
    buffer = io.StringIO()
    table = csv.writer(buffer, lineterminator="\n")
    table.writerow(["address", "symbol", "name", "system", "module", "size", "status"])
    for n in sorted(nodes, key=lambda n: n["addr"]):
        table.writerow([n["address"], n["canonical_symbol"], n.get("display_name", ""), system_of(n),
                        n.get("module", ""), n.get("size", ""), n.get("name_status", "")])
    (out / "function_names.csv").write_text(buffer.getvalue(), encoding="utf-8", newline="\n")
    (out / "name_audit.md").write_text(audit(nodes), encoding="utf-8", newline="\n")
    return {"exported": len(named)}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=str(ROOT / "docs/progress"))
    parser.add_argument("--audit", action="store_true")
    args = parser.parse_args()
    nodes = json.loads(Path(args.out, "functions.json").read_text(encoding="utf-8"))["functions"]
    if args.audit:
        print(audit(nodes))
    else:
        print(write_outputs(nodes, args.out))
